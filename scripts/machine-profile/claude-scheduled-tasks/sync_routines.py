#!/usr/bin/env python3
"""Keep every approved Claude desktop routine registered on whatever account is signed in.

Desktop routines are registered per Claude ACCOUNT (store:
~/Library/Application Support/Claude/claude-code-sessions/<account>/<org>/scheduled-tasks.json),
while their SKILL.md folders under ~/.claude/scheduled-tasks/ are shared by every account on the
Mac. Switching accounts therefore silently drops routines. This script reads routines.json (the
approved list) and the signed-in account's store, and prints what the account is missing.

It never writes the desktop app's store (the app owns it). The agent running it creates each
missing routine with the scheduled-tasks MCP `create_scheduled_task`, passing the printed
taskId, cronExpression, title, description and prompt (notifyOnCompletion false). Re-running is
idempotent: a routine already registered from the same source folder is reported as present.

Every prompt gets the ONE claim preface (CLAIM_PREFACE below; doc: claim-preface.md) so that,
with the routine on several accounts, `schedule_claim` lets exactly one fire run each window.

  python3 sync_routines.py            # plan for the signed-in account (JSON on stdout)
  python3 sync_routines.py --check    # also flag registered copies whose prompt drifted
  python3 sync_routines.py --prompt <source>   # print the composed prompt for one routine
  python3 sync_routines.py --write    # write the composed prompt into every registered copy's
                                      # SKILL.md (frontmatter kept): finishes a create made with a
                                      # placeholder prompt and repairs drift
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
from datetime import date
from pathlib import Path

HERE = Path(__file__).resolve().parent
MANIFEST = HERE / "routines.json"
TASKS_DIR = Path.home() / ".claude" / "scheduled-tasks"
STORE_ROOT = Path.home() / "Library" / "Application Support" / "Claude" / "claude-code-sessions"

PREFACE_START = "<!-- claim-preface v1"
PREFACE_END = "<!-- claim-preface end -->"

WINDOW_ARG = {
    "daily": "",
    "ampm": 'window_key="<date>am" before noon or "<date>pm" from noon (date = the YYYY-MM-DD part), ',
    "hour": 'window_key="<the YYYY-MM-DDTHH line>", ',
}

CLAIM_PREFACE = """<!-- claim-preface v1 — generated by matrx-ship/scripts/machine-profile/claude-scheduled-tasks/sync_routines.py; edit it there, never here -->
STEP 0 — ONE RUN PER WINDOW ACROSS EVERY ACCOUNT AND MACHINE. Do this before anything else.
This routine is registered on every Claude account that signs into the desktop app, so a twin may fire minutes apart. The AI Dream MCP tool `schedule_claim` decides which one runs (load it with ToolSearch "select:mcp__plugin_matrx_aidream__schedule_claim" if it is deferred).
1. Run in Bash: echo "${{CLAUDE_CODE_USER_EMAIL:-claude-desktop}}"; hostname -s; TZ=America/Los_Angeles date +%Y-%m-%dT%H
2. Call schedule_claim(task_key="{key}", account=<the email>, machine=<the hostname>, {window}lease_minutes={lease}).
3. claimed false or refused set: STOP. Do no work. Reply with one line: "Skipped: {key} window <window_key> already handled by <already_claimed_by>" (or the refusal reason).
4. claimed true: do the work below and hold it to the returned limits. If the instructions below also claim or complete "{key}", step 2 and step 5 replace those calls.
5. Last step, always: schedule_claim(action="complete", task_key="{key}", account=<the same email>, {window}status="completed" (or "failed" / "abandoned"), result_note="<one line>", turns=<n>, minutes=<n>).
If the MCP is unreachable, use the fallback in "The claim protocol" of /Users/armanisadeghi/code/common-docs/operations/scheduled-tasks.md.
<!-- claim-preface end -->"""


def load_manifest() -> list[dict]:
    return json.loads(MANIFEST.read_text())["routines"]


def split_skill(path: Path) -> tuple[str, str]:
    """(description, body) of a SKILL.md, body without frontmatter and without any old preface."""
    text = path.read_text()
    desc = ""
    m = re.match(r"^---\n(.*?)\n---\n?", text, re.S)
    if m:
        for line in m.group(1).splitlines():
            if line.startswith("description:"):
                desc = line.split(":", 1)[1].strip().strip('"')
        text = text[m.end():]
    if PREFACE_START in text and PREFACE_END in text:
        text = text[text.index(PREFACE_END) + len(PREFACE_END):]
    return desc, text.strip("\n")


def compose(routine: dict) -> dict:
    desc, body = split_skill(TASKS_DIR / routine["source"] / "SKILL.md")
    if routine.get("preface", True):
        preface = CLAIM_PREFACE.format(
            key=routine["task_key"],
            window=WINDOW_ARG[routine.get("window", "daily")],
            lease=routine.get("lease_minutes", 90),
        )
        prompt = f"{preface}\n\n{body}\n"
    else:
        prompt = f"{body}\n"
    return {"description": desc, "prompt": prompt}


def account_store() -> tuple[str, Path]:
    acct = os.environ.get("CLAUDE_CODE_ACCOUNT_UUID", "")
    org = os.environ.get("CLAUDE_CODE_ORGANIZATION_UUID", "")
    if not acct or not org:
        sys.exit("CLAUDE_CODE_ACCOUNT_UUID / CLAUDE_CODE_ORGANIZATION_UUID not set: run inside a Claude desktop session.")
    return acct, STORE_ROOT / acct / org / "scheduled-tasks.json"


def registered(store: Path) -> list[dict]:
    if not store.exists():
        return []
    return json.loads(store.read_text()).get("scheduledTasks", [])


def source_of(task: dict, sources: set[str]) -> str | None:
    """Which manifest routine a registered task is (its own folder, or a '<source>-acct-*' copy)."""
    tid = task.get("id", "")
    if tid in sources:
        return tid
    base = re.sub(r"-acct-[0-9a-f]{4}$", "", tid)
    return base if base in sources else None


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="flag registered copies whose prompt drifted")
    ap.add_argument("--prompt", metavar="SOURCE", help="print the composed prompt for one routine")
    ap.add_argument("--write", action="store_true", help="write composed prompts into registered copies")
    args = ap.parse_args()

    routines = load_manifest()
    if args.prompt:
        r = next((x for x in routines if x["source"] == args.prompt), None)
        if r is None:
            sys.exit(f"unknown routine {args.prompt!r}")
        print(compose(r)["prompt"], end="")
        return 0

    acct, store = account_store()
    tasks = registered(store)
    sources = {r["source"] for r in routines}
    have: dict[str, dict] = {}
    for t in tasks:
        s = source_of(t, sources)
        if s and t.get("enabled", True) and t.get("cronExpression"):
            have[s] = t

    today = date.today().isoformat()
    plan = {"account": acct, "store": str(store), "present": [], "missing": [], "skipped": [], "drifted": []}
    for r in routines:
        if r.get("until") and today > r["until"]:
            plan["skipped"].append({"source": r["source"], "reason": f"approval window ended {r['until']}"})
            continue
        if r["source"] in have:
            t = have[r["source"]]
            plan["present"].append({"source": r["source"], "taskId": t["id"], "cron": t.get("cronExpression")})
            if args.write:
                path = Path(t["filePath"])
                text = path.read_text()
                fm = re.match(r"^---\n.*?\n---\n?", text, re.S)
                new = (fm.group(0).rstrip("\n") + "\n\n" if fm else "") + compose(r)["prompt"]
                if new != text:
                    path.write_text(new)
                    plan.setdefault("written", []).append(t["id"])
            if args.check:
                want = compose(r)["prompt"].strip()
                got = split_skill(Path(t["filePath"]))[1].strip() if t["id"] != r["source"] else None
                if got is not None and want.split(PREFACE_END)[-1].strip() != got:
                    plan["drifted"].append({"source": r["source"], "taskId": t["id"]})
            continue
        free_id = r["source"] if not (TASKS_DIR / r["source"]).exists() else f"{r['source']}-acct-{acct[:4]}"
        c = compose(r)
        plan["missing"].append({
            "taskId": free_id,
            "cronExpression": r["cron"],
            "title": r["title"],
            "description": c["description"],
            "notifyOnCompletion": False,
            "prompt_command": f"python3 {Path(__file__).resolve()} --prompt {r['source']}",
        })
    print(json.dumps(plan, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
